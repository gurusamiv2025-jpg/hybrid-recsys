"""Reproduce every number, table and figure in REPORT.md.

    python scripts/run_experiment.py                 # full run, 3 seeds (~45 min)
    python scripts/run_experiment.py --quick         # tiny grid, 1 seed (~4 min)
    python scripts/run_experiment.py --no-genome     # skip the 260 MB ML-25M download
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from dataclasses import asdict
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from hybridrec import analysis as A  # noqa: E402
from hybridrec.data import load  # noqa: E402
from hybridrec.experiment import Config, log, run_seed  # noqa: E402


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data-dir", default=str(ROOT / "data"))
    ap.add_argument("--out-dir", default=str(ROOT / "results"))
    ap.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2])
    ap.add_argument("--k", type=int, default=10)
    ap.add_argument("--horizon", type=int, default=20,
                    help="evaluate on each user's next N held-out interactions (0 = all of them)")
    ap.add_argument("--no-genome", action="store_true", help="content features from genres/year/title only")
    ap.add_argument("--quick", action="store_true", help="small grids and one seed, for a fast sanity run")
    args = ap.parse_args()

    cfg = Config(k=args.k, horizon=args.horizon or None)
    seeds = args.seeds
    if args.quick:
        cfg, seeds = cfg.quick(), seeds[:1]
    out = Path(args.out_dir)
    (out / "figures").mkdir(parents=True, exist_ok=True)

    t0 = time.time()
    ml = load(args.data_dir, use_genome=not args.no_genome)
    log(f"loaded {len(ml.ratings):,} ratings, {len(ml.users):,} users, {len(ml.movies):,} movies"
        + (f", genome for {len(ml.genome):,} movies" if ml.genome is not None else ""))

    results = [run_seed(ml, cfg, s, keep_artifacts=(i == 0)) for i, s in enumerate(seeds)]
    first, k = results[0], cfg.k

    log("writing tables, figures and failure analysis")
    A.plot_buckets(results, k, out / "figures" / "ndcg_by_history.png")
    A.plot_gate(first.gate, out / "figures" / "gate_weights.png")
    A.plot_mmr(first.mmr, k, out / "figures" / "mmr_tradeoff.png")
    fail = A.failure_analysis(ml, first, k, out)

    head = A.headline(results, k)
    lift = A.lift_table(results, k)
    buckets = A.bucket_table(results, k)
    beyond = (pd.concat([r.beyond for r in results])
              .groupby(["slice", "model"], sort=False).mean(numeric_only=True).reset_index())
    beyond = beyond[beyond["slice"] != "all"]
    gates = [{"seed": r.seed, **r.als_params, **asdict(r.gate)} for r in results]
    abl = pd.concat([r.ablation for r in results]).groupby("features", sort=False).mean().reset_index()
    spread = "std across seeds" if len(results) > 1 else "standard error over users"

    md = [f"# Results (seeds {seeds}, K={k})\n",
          f"Generated by `scripts/run_experiment.py` in {(time.time() - t0) / 60:.1f} min. "
          f"Values are mean ± {spread}. Users are judged on their next "
          f"{cfg.horizon or 'all'} held-out interactions.\n",
          "## Headline metrics by slice\n", A.md_table(head), "",
          "## NDCG lift over global popularity\n", A.md_table(lift), "",
          f"## NDCG@{k} by user history (mean over seeds)\n", A.md_table(buckets), "",
          "## Beyond-accuracy (top-10 lists)\n", A.md_table(beyond, ".3f"), "",
          f"## Diversity re-ranking (MMR on the adaptive hybrid, seed {first.seed})\n",
          A.md_table(first.mmr, ".4f"), "",
          f"## Content-feature ablation (NDCG@{k}, mean over seeds)\n", A.md_table(abl), "",
          "## Tuned hyper-parameters\n", A.md_table(pd.DataFrame(gates), ".3g"), "",
          f"## Top gate settings on validation (seed {first.seed})\n",
          A.md_table(first.tuning["gate"].head(8), ".4f"), "",
          "## Failure analysis (adaptive hybrid, seed %d)\n" % first.seed,
          "### NDCG by how niche the user's held-out likes are\n", fail["niche"], "",
          "### Spearman correlation of per-user NDCG with user properties\n", fail["correlations"], "",
          "### Personalisation of the top-10 lists\n", fail["personalisation"], "",
          "### Popularity bias (percentile, 1 = most popular item)\n", fail["popularity_bias"], "",
          "### Cold items: rank among cold candidates by item history and genome availability\n",
          fail["cold_items"], "",
          "### Cold items the hybrid ranks worst (>= 20 held-out likes)\n", fail["worst_cold_items"], "",
          "### Cold items the hybrid ranks best\n", fail["best_cold_items"], "",
          "### Worked examples\n", fail["examples"]]
    (out / "summary.md").write_text("\n".join(md), encoding="utf-8")

    json.dump({"config": {"k": k, "horizon": cfg.horizon, "seeds": seeds, "genome": not args.no_genome, "quick": args.quick},
               "tuned": gates,
               "headline": head.to_dict(orient="records"),
               "by_history": buckets.to_dict(orient="records"),
               "beyond_accuracy": beyond.to_dict(orient="records"),
               "mmr": first.mmr.to_dict(orient="records"),
               "ablation": abl.to_dict(orient="records")},
              open(out / "metrics.json", "w"), indent=2, default=float)
    first.per_user.to_csv(out / f"per_user_seed{first.seed}.csv.gz", index=False)
    log(f"done in {(time.time() - t0) / 60:.1f} min -> {out / 'summary.md'}")


if __name__ == "__main__":
    main()
